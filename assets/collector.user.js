// ==UserScript==
// @name         X Bookmarks Collector (x-bookmark-organizer fallback)
// @namespace    https://github.com/x-bookmark-organizer
// @version      1.2.0
// @description  Passive X bookmark exporter. Reads Bookmarks GraphQL responses as you scroll; downloads bookmarks_raw.jsonl for: python xb.py import --fixture bookmarks_raw.jsonl. Works on /i/bookmarks and the Bookmarks tab of /i/history.
// @match        https://x.com/*
// @match        https://twitter.com/*
// @run-at       document-start
// @grant        none
// @noframes
// ==/UserScript==
// Adapted from SaveBox assets/collector.user.js (same envelope contract).
//
// Passive network interception only: reads GraphQL timeline responses the
// page itself loads. No login, no cookies, no auth tokens, no storage
// access, no X API calls generated by this script, nothing sent anywhere.
(function () {
  "use strict";
  // Match any X GraphQL endpoint; the operation name is extracted
  // separately and is NOT required to contain "Bookmarks" (the History
  // page may use a different operation name / transport).
  var GRAPHQL_RE = /\/i\/api\/graphql\//;
  var OP_RE = /\/i\/api\/graphql\/[^/]+\/([^/?#]+)/;
  // Strong bookmark signal when available (preferred, not mandatory).
  var BOOKMARK_OP_RE = /bookmark/i;
  var PREFIX = "[X Bookmark Collector]";
  var captured = [], seen = {}, page = 0;
  var diag = [];
  function iso() { return new Date().toISOString().replace(/\.\d{3}Z$/, "Z"); }
  function log() {
    try {
      var args = [PREFIX].concat(Array.prototype.slice.call(arguments));
      if (typeof console !== "undefined" && console.log) {
        console.log.apply(console, args);
      }
    } catch (e) {}
  }
  function opNameFromUrl(u) {
    try {
      var m = String(u || "").match(OP_RE);
      return m ? m[1] : "";
    } catch (e) { return ""; }
  }
  function instr(g) {
    if (!g || typeof g !== "object") return [];
    var d = g.data || g;
    var keys = ["bookmark_timeline_v2", "bookmark_timeline", "bookmarks"];
    for (var i = 0; i < keys.length; i++) {
      var tl = d[keys[i]];
      if (tl && tl.timeline && tl.timeline.instructions) {
        return tl.timeline.instructions;
      }
    }
    return [];
  }
  // Generic fallback: find any timeline.instructions arrays anywhere in a
  // GraphQL response so non-"Bookmarks" operation names on /i/history are
  // still captured. Only arrays containing entryId-bearing entries count.
  function findInstructions(data) {
    var out = [], seenArr = [];
    function isInstrArray(a) {
      if (!Array.isArray(a)) return false;
      for (var i = 0; i < a.length; i++) {
        var n = a[i];
        if (!n || typeof n !== "object") continue;
        var es = n.entries;
        if (Array.isArray(es)) {
          for (var j = 0; j < es.length; j++) {
            if (es[j] && typeof es[j].entryId === "string") return true;
          }
        }
        if (typeof n.entryId === "string") return true;
      }
      return false;
    }
    function pushUnique(a) {
      for (var i = 0; i < seenArr.length; i++) {
        if (seenArr[i] === a) return;
      }
      seenArr.push(a);
      out.push(a);
    }
    var known = instr(data);
    if (known && known.length) pushUnique(known);
    try {
      var stack = [{ v: data, d: 0 }];
      var visited = [];
      while (stack.length) {
        var cur = stack.pop();
        var v = cur.v, depth = cur.d;
        if (!v || typeof v !== "object" || depth > 8) continue;
        var skip = false;
        for (var k = 0; k < visited.length; k++) {
          if (visited[k] === v) { skip = true; break; }
        }
        if (skip) continue;
        visited.push(v);
        if (Array.isArray(v)) {
          if (isInstrArray(v)) pushUnique(v);
          for (var a = 0; a < v.length; a++) {
            if (v[a] && typeof v[a] === "object") {
              stack.push({ v: v[a], d: depth + 1 });
            }
          }
          continue;
        }
        if (v.timeline && v.timeline.instructions &&
            isInstrArray(v.timeline.instructions)) {
          pushUnique(v.timeline.instructions);
        }
        if (isInstrArray(v.instructions)) pushUnique(v.instructions);
        for (var key in v) {
          if (!Object.prototype.hasOwnProperty.call(v, key)) continue;
          var child = v[key];
          if (child && typeof child === "object") {
            stack.push({ v: child, d: depth + 1 });
          }
        }
      }
    } catch (e) {}
    // Flatten instruction arrays into one list of instruction nodes.
    var flat = [];
    for (var f = 0; f < out.length; f++) {
      var arr = out[f];
      for (var g = 0; g < arr.length; g++) flat.push(arr[g]);
    }
    return flat;
  }
  function countTweetLike(ins) {
    var n = 0;
    try {
      (ins || []).forEach(function (node) {
        (node.entries || []).forEach(function (e) {
          if (e && typeof e.entryId === "string" &&
              e.entryId.indexOf("tweet-") === 0) n++;
        });
        if (node && typeof node.entryId === "string" &&
            node.entryId.indexOf("tweet-") === 0) n++;
      });
    } catch (e) {}
    return n;
  }
  function hasBookmarkSignal(url, data) {
    try {
      if (BOOKMARK_OP_RE.test(opNameFromUrl(url))) return true;
    } catch (e) {}
    try {
      if (instr(data) && instr(data).length) return true;
    } catch (e) {}
    try {
      var s = JSON.stringify(data);
      if (typeof s === "string") {
        if (s.length > 200000) s = s.slice(0, 200000);
        if (/bookmark/i.test(s)) return true;
      }
    } catch (e) {}
    return false;
  }
  // Shared envelope/dedup/cursor logic (downstream import contract).
  function ingestNodes(nodes) {
    var tweets = 0, cursor = "";
    (nodes || []).forEach(function (n) {
      var entries = n.entries || (n.entryId ? [n] : []);
      entries.forEach(function (e) {
        if (!e || !e.entryId) return;
        if (e.entryId.indexOf("tweet-") === 0) {
          var id = e.entryId.replace("tweet-", "");
          if (!seen[id]) {
            seen[id] = 1; tweets++;
            captured.push({ captured_at: iso(), cursor: cursor,
              entry_id: e.entryId, page: page, raw: e,
              sort_index: e.sortIndex || "", status_id: id });
          }
        } else if (e.entryId.indexOf("cursor-bottom-") === 0) {
          cursor = (e.content && e.content.value) || cursor;
        }
      });
    });
    if (tweets) { page++; update(); }
    return tweets;
  }
  function recordDiag(info) {
    try {
      var entry = {
        op: info.op || "",
        method: info.method || "",
        transport: info.transport || "",
        status: typeof info.status === "number" ? info.status : 0,
        jsonOk: !!info.jsonOk,
        tweetLike: typeof info.tweetLike === "number" ? info.tweetLike : 0,
        at: iso()
      };
      diag.push(entry);
      if (diag.length > 20) diag.splice(0, diag.length - 20);
      // Never log cookies, headers, auth values, request bodies, or
      // response bodies -- only the small summary above.
      log("no tweets in GraphQL response",
        JSON.stringify(entry));
    } catch (e) {}
  }
  function handleGraphql(data, meta) {
    try {
      meta = meta || {};
      if (!isCaptureActive(meta.url, data)) return;
      var nodes = findInstructions(data);
      var like = countTweetLike(nodes);
      var before = count();
      ingestNodes(nodes);
      var gained = count() - before;
      if (!gained) {
        recordDiag({ op: meta.op || opNameFromUrl(meta.url),
          method: meta.method || "GET", transport: meta.transport || "",
          status: meta.status || 0, jsonOk: true, tweetLike: like });
      } else {
        log("captured " + gained + " tweet(s) from op '" +
          (meta.op || opNameFromUrl(meta.url) || "?") + "' via " +
          (meta.transport || "?"));
      }
    } catch (e) {}
  }
  function urlOf(input) {
    try {
      if (typeof input === "string") return input;
      if (input && typeof input.url === "string") return input.url;
    } catch (e) {}
    return "";
  }
  function methodOf(input, init) {
    try {
      if (init && typeof init.method === "string") return init.method;
      if (input && typeof input.method === "string") return input.method;
    } catch (e) {}
    return "GET";
  }
  // ---- transport 1: fetch (cloned body so the page is unaffected) ----
  try {
    if (typeof window.fetch === "function") {
      var f = window.fetch;
      window.fetch = function (input, init) {
        var u = urlOf(input);
        if (typeof input !== "string" && input &&
            typeof input !== "object") {
          try { u = String(input); } catch (e) {}
        }
        var p;
        try {
          p = f.apply(this, arguments);
        } catch (e) { throw e; }
        if (u && GRAPHQL_RE.test(u)) {
          var method = methodOf(input, init);
          var op = opNameFromUrl(u);
          try {
            p.then(function (r) {
              try {
                var status = (r && typeof r.status === "number") ?
                  r.status : 0;
                r.clone().json().then(function (d) {
                  try {
                    handleGraphql(d, { url: u, op: op, method: method,
                      transport: "fetch", status: status });
                  } catch (e) {}
                }).catch(function () {
                  try {
                    if (isCaptureActive(u, null)) {
                      recordDiag({ op: op, method: method,
                        transport: "fetch", status: status,
                        jsonOk: false, tweetLike: 0 });
                    }
                  } catch (e) {}
                });
              } catch (e) {}
            }).catch(function () {});
          } catch (e) {}
        }
        return p;
      };
    }
  } catch (e) {}
  // ---- transport 2: XMLHttpRequest (responseText; page unaffected) ----
  try {
    if (typeof XMLHttpRequest !== "undefined" &&
        XMLHttpRequest.prototype) {
      var _open = XMLHttpRequest.prototype.open;
      var _send = XMLHttpRequest.prototype.send;
      if (typeof _open === "function") {
        XMLHttpRequest.prototype.open = function (method, url) {
          try {
            this._xbcMethod = method || "GET";
            this._xbcUrl = url || "";
          } catch (e) {}
          return _open.apply(this, arguments);
        };
      }
      if (typeof _send === "function") {
        XMLHttpRequest.prototype.send = function () {
          try {
            var xhr = this;
            var u = xhr._xbcUrl || "";
            if (u && GRAPHQL_RE.test(u)) {
              var method = xhr._xbcMethod || "GET";
              var op = opNameFromUrl(u);
              var onLoad = function () {
                try {
                  var status = (typeof xhr.status === "number") ?
                    xhr.status : 0;
                  var text = xhr.responseText;
                  var d;
                  try {
                    d = JSON.parse(text);
                  } catch (e) {
                    if (isCaptureActive(u, null)) {
                      recordDiag({ op: op, method: method,
                        transport: "xhr", status: status,
                        jsonOk: false, tweetLike: 0 });
                    }
                    return;
                  }
                  handleGraphql(d, { url: u, op: op, method: method,
                    transport: "xhr", status: status });
                } catch (e) {}
              };
              try {
                if (typeof xhr.addEventListener === "function") {
                  xhr.addEventListener("load", onLoad);
                } else {
                  var prev = xhr.onreadystatechange;
                  xhr.onreadystatechange = function () {
                    try {
                      if (xhr.readyState === 4) onLoad();
                    } catch (e) {}
                    if (typeof prev === "function") {
                      try { return prev.apply(this, arguments); }
                      catch (e) {}
                    }
                  };
                }
              } catch (e) {}
            }
          } catch (e) {}
          return _send.apply(this, arguments);
        };
      }
    }
  } catch (e) {}
  function count() {
    var n = 0;
    for (var k in seen) { n++; }
    return n;
  }
  var box = null, label = null;
  function update() { if (label) label.textContent = "Captured " + count() + " bookmarks"; }
  function locText() {
    try { return (location.pathname || "") + (location.search || "") + (location.hash || ""); }
    catch (e) { return ""; }
  }
  function isLegacyRoute() {
    try { return location.pathname.indexOf("/i/bookmarks") === 0; }
    catch (e) { return false; }
  }
  function isHistoryRoute() {
    try { return location.pathname.indexOf("/i/history") === 0; }
    catch (e) { return false; }
  }
  function domBookmarksSelected() {
    // Returns true = Bookmarks tab active, false = another tab active,
    // null = unknown. Uses generic ARIA signals only (no X-specific
    // class names, testids, or markup assumptions).
    try {
      var tabs = document.querySelectorAll('[role="tab"]');
      for (var i = 0; i < tabs.length; i++) {
        if (tabs[i].getAttribute("aria-selected") === "true") {
          var name = tabs[i].getAttribute("aria-label") || tabs[i].textContent || "";
          if (/bookmark/i.test(name)) return true;
          if (name.replace(/\s/g, "")) return false;
        }
      }
      var cur = document.querySelectorAll('a[aria-current="page"], [aria-selected="true"]');
      for (var j = 0; j < cur.length; j++) {
        var t = cur[j].getAttribute("aria-label") || cur[j].textContent || "";
        if (/bookmark/i.test(t)) return true;
      }
    } catch (e) {}
    return null;
  }
  function isBookmarksView() {
    // Legacy route is always the bookmarks view (no tabs involved).
    if (isLegacyRoute()) return true;
    if (!isHistoryRoute()) return false;
    // On /i/history the pathname prefix itself is "history", so only
    // inspect what follows it (subpath + query + hash) for tab signals.
    var rest = locText().slice("/i/history".length);
    if (/bookmark/i.test(rest)) return true;
    if (/like/i.test(rest)) return false;
    if (/video|article/i.test(rest)) return false;
    var dom = domBookmarksSelected();
    if (dom !== null) return dom;
    // Fail open on a bare /i/history with unreadable tabs so the
    // Download button still appears reliably; capture itself remains
    // gated on Bookmarks GraphQL responses (see isCaptureActive below),
    // so other tabs simply capture nothing.
    return true;
  }
  // Ingestion gate (checked at response time so SPA tab switches take
  // effect immediately). Unlike the UI helper above, an unknown tab
  // state does NOT fail open: without a positive Bookmarks signal the
  // response is dropped so Likes/Videos/Articles are never captured.
  function isCaptureActive(url, data) {
    try {
      if (isLegacyRoute()) return true;
      if (!isHistoryRoute()) return false;
      var rest = locText().slice("/i/history".length);
      if (/bookmark/i.test(rest)) return true;
      if (/like/i.test(rest)) return false;
      if (/video|article/i.test(rest)) return false;
      var dom = domBookmarksSelected();
      if (dom === true) return true;
      if (dom === false) return false;
      return hasBookmarkSignal(url, data);
    } catch (e) { return false; }
  }
  function refresh() {
    if (!box) { init(); return; }
    try { box.style.display = isBookmarksView() ? "" : "none"; } catch (e) {}
  }
  function download() {
    var blob = new Blob([captured.map(function (o) {
      return JSON.stringify(o);
    }).join("\n") + "\n"], { type: "application/json" });
    var a = document.createElement("a");
    a.href = URL.createObjectURL(blob);
    a.download = "bookmarks_raw.jsonl";
    a.click();
  }
  function init() {
    if (box) { refresh(); return; }
    if (!document.body) return;
    box = document.createElement("div");
    box.style.cssText = "position:fixed;z-index:999999;bottom:16px;right:16px;background:#15202b;color:#fff;padding:10px;border-radius:10px;font:13px sans-serif";
    label = document.createElement("div");
    var b = document.createElement("button");
    b.textContent = "Download bookmarks_raw.jsonl";
    b.onclick = download;
    box.appendChild(label); box.appendChild(b);
    document.body.appendChild(box); update();
    refresh();
  }
  // X is an SPA: tab switches and in-app navigation do not reload the
  // page, so re-check the current view on history changes, tab
  // attribute flips, and a periodic fallback.
  try {
    var _ps = history.pushState, _rs = history.replaceState;
    history.pushState = function () {
      var r = _ps.apply(this, arguments);
      setTimeout(refresh, 0);
      return r;
    };
    history.replaceState = function () {
      var r = _rs.apply(this, arguments);
      setTimeout(refresh, 0);
      return r;
    };
  } catch (e) {}
  window.addEventListener("popstate", function () { setTimeout(refresh, 0); });
  window.addEventListener("hashchange", function () { setTimeout(refresh, 0); });
  var _mt = null;
  function watchTabs() {
    try {
      var target = document.documentElement || document.body;
      if (!target || typeof MutationObserver !== "function") return;
      var mo = new MutationObserver(function () {
        if (_mt) return;
        _mt = setTimeout(function () { _mt = null; refresh(); }, 300);
      });
      mo.observe(target, { childList: true, subtree: true,
        attributes: true, attributeFilter: ["aria-selected", "aria-current"] });
    } catch (e) {}
  }
  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", function () { watchTabs(); init(); });
  } else { watchTabs(); init(); }
  setInterval(refresh, 1500);
})();
